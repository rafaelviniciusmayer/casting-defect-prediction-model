"""
Item 1.3 — Results with and without SMOTE (ablation study).

Reviewer question: "What is the actual contribution of SMOTE? Is the combination
SMOTE + cost-sensitive learning really better than cost-sensitive learning alone?"

Compares, for each model, two conditions in the SAME CV pipeline (5 folds):
  (a) without SMOTE — cost-sensitive learning only
      (pos_weight in the NN, class_weight='balanced' in RF, scale_pos_weight in XGBoost)
  (b) with SMOTE — SMOTE inside the training fold + cost-sensitive learning

Metrics compared: recall, precision, F1-micro, F1-macro and training time.

The decision (keep or remove SMOTE from the official configuration) is recorded in
the Phase 1 checkpoint, generated by run_phase1_validation.py.

This module does NOT train anything: it consumes CVResults already computed by the
unified pipeline, orchestrated by run_phase1_validation.py.
"""

from __future__ import annotations

from typing import Any, Dict, List

import pandas as pd

from unified_cv_pipeline import (
    CVResult,
    METRIC_KEYS,
    dataframe_to_markdown,
    format_mean_std,
)


def build_smote_comparison_payload(
    cv_results_without: Dict[str, CVResult],
    cv_results_with: Dict[str, CVResult],
) -> Dict[str, Any]:
    """Builds the comparison payload from already computed CVResults."""
    comparison = []
    for model_type, cv_with in cv_results_with.items():
        cv_without = cv_results_without[model_type]

        def _condition_dict(cv: CVResult) -> Dict[str, Any]:
            return {
                "use_smote": cv.use_smote,
                "cv_val_mean": cv.val_mean,
                "cv_val_std": cv.val_std,
                "cv_train_mean": cv.train_mean,
                "total_train_time_sec": cv.total_train_time_sec,
            }

        without = _condition_dict(cv_without)
        with_sm = _condition_dict(cv_with)
        delta = {
            key: with_sm["cv_val_mean"][key] - without["cv_val_mean"][key]
            for key in METRIC_KEYS
        }
        delta["train_time_sec"] = (
            with_sm["total_train_time_sec"] - without["total_train_time_sec"]
        )

        comparison.append(
            {
                "model_type": model_type,
                "model_name": cv_with.model_name,
                "without_smote": without,
                "with_smote": with_sm,
                "delta_with_minus_without": delta,
            }
        )
    return {"models": comparison}


def build_smote_comparison_table(payload: Dict[str, Any]) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for model in payload["models"]:
        name = model["model_name"]
        for condition_key, condition_label in (
            ("without_smote", "No SMOTE"),
            ("with_smote", "With SMOTE"),
        ):
            data = model[condition_key]
            vm = data["cv_val_mean"]
            vs = data["cv_val_std"]
            rows.append(
                {
                    "Model": name,
                    "Condition": condition_label,
                    "Recall (CV)": format_mean_std(vm["recall_micro"], vs["recall_micro"]),
                    "Precision (CV)": format_mean_std(
                        vm["precision_micro"], vs["precision_micro"]
                    ),
                    "F1-micro (CV)": format_mean_std(vm["f1_micro"], vs["f1_micro"]),
                    "F1-macro (CV)": format_mean_std(vm["f1_macro"], vs["f1_macro"]),
                    "CV Time (s)": f"{data['total_train_time_sec']:.1f}",
                }
            )
        delta = model["delta_with_minus_without"]
        rows.append(
            {
                "Model": name,
                "Condition": "Delta (With - No)",
                "Recall (CV)": f"{delta['recall_micro']:+.4f}",
                "Precision (CV)": f"{delta['precision_micro']:+.4f}",
                "F1-micro (CV)": f"{delta['f1_micro']:+.4f}",
                "F1-macro (CV)": f"{delta['f1_macro']:+.4f}",
                "CV Time (s)": f"{delta['train_time_sec']:+.1f}",
            }
        )
    return pd.DataFrame(rows)


def build_smote_recommendations(payload: Dict[str, Any]) -> List[str]:
    """Heuristic to recommend keeping or removing SMOTE, per model."""
    recommendations = []
    for model in payload["models"]:
        delta = model["delta_with_minus_without"]
        recall_gain = delta["recall_micro"]
        f1_gain = delta["f1_micro"]
        gap_with = (
            model["with_smote"]["cv_train_mean"]["f1_micro"]
            - model["with_smote"]["cv_val_mean"]["f1_micro"]
        )
        gap_without = (
            model["without_smote"]["cv_train_mean"]["f1_micro"]
            - model["without_smote"]["cv_val_mean"]["f1_micro"]
        )
        overfit_increase = gap_with - gap_without

        if f1_gain >= 0.01 or recall_gain >= 0.02:
            if overfit_increase <= 0.05:
                rec = (
                    f"**{model['model_name']}**: keep SMOTE "
                    f"(ΔF1={f1_gain:+.4f}, ΔRecall={recall_gain:+.4f}, "
                    f"train-val gap increase={overfit_increase:+.4f})."
                )
            else:
                rec = (
                    f"**{model['model_name']}**: SMOTE improves the metrics "
                    f"(ΔF1={f1_gain:+.4f}), but increases the train-val gap "
                    f"({overfit_increase:+.4f}) — assess the trade-off."
                )
        else:
            rec = (
                f"**{model['model_name']}**: SMOTE brings no relevant gain "
                f"(ΔF1={f1_gain:+.4f}, ΔRecall={recall_gain:+.4f}) — "
                f"consider cost-sensitive learning only."
            )
        recommendations.append(rec)
    return recommendations


def decide_official_smote(payload: Dict[str, Any]) -> Dict[str, Any]:
    """
    Global Phase 1 decision: keep SMOTE in the official configuration?

    Criterion: SMOTE is kept if, on average across the models, it brings a gain
    of F1-micro >= 0.005 or of recall >= 0.01 on the CV validation, without a
    mean increase of the train-val gap above 0.05.
    """
    f1_gains = []
    recall_gains = []
    gap_increases = []
    for model in payload["models"]:
        delta = model["delta_with_minus_without"]
        f1_gains.append(delta["f1_micro"])
        recall_gains.append(delta["recall_micro"])
        gap_with = (
            model["with_smote"]["cv_train_mean"]["f1_micro"]
            - model["with_smote"]["cv_val_mean"]["f1_micro"]
        )
        gap_without = (
            model["without_smote"]["cv_train_mean"]["f1_micro"]
            - model["without_smote"]["cv_val_mean"]["f1_micro"]
        )
        gap_increases.append(gap_with - gap_without)

    avg_f1_gain = sum(f1_gains) / len(f1_gains)
    avg_recall_gain = sum(recall_gains) / len(recall_gains)
    avg_gap_increase = sum(gap_increases) / len(gap_increases)

    keep_smote = (
        (avg_f1_gain >= 0.005 or avg_recall_gain >= 0.01)
        and avg_gap_increase <= 0.05
    )

    return {
        "keep_smote": bool(keep_smote),
        "avg_f1_micro_gain": avg_f1_gain,
        "avg_recall_gain": avg_recall_gain,
        "avg_train_val_gap_increase": avg_gap_increase,
        "criteria": (
            "Keep SMOTE if the mean gain of F1-micro >= 0.005 or of recall >= 0.01 "
            "on validation (CV), with a mean train-val gap increase <= 0.05."
        ),
    }


def build_smote_markdown(
    df: pd.DataFrame,
    recommendations: List[str],
    decision: Dict[str, Any],
) -> str:
    decision_label = (
        "**SMOTE KEPT** in the official configuration"
        if decision["keep_smote"]
        else "**SMOTE REMOVED** — the official configuration now uses cost-sensitive learning only"
    )
    lines = [
        "# Phase 1.3 — SMOTE Contribution (ablation)\n",
        "Side-by-side comparison using the same CV pipeline (5 folds). "
        "In both conditions, cost-sensitive learning remains active "
        "(pos_weight in the NN, class_weight='balanced' in RF, scale_pos_weight in XGBoost).\n",
        dataframe_to_markdown(df),
        "",
        "## Recommendations per model\n",
    ]
    lines.extend(f"- {r}" for r in recommendations)
    lines += [
        "",
        "## Phase 1 decision\n",
        f"- {decision_label}",
        f"- Mean F1-micro gain: {decision['avg_f1_micro_gain']:+.4f}",
        f"- Mean recall gain: {decision['avg_recall_gain']:+.4f}",
        f"- Mean train-val gap increase: {decision['avg_train_val_gap_increase']:+.4f}",
        f"- Criterion: {decision['criteria']}",
        "",
    ]
    return "\n".join(lines)
